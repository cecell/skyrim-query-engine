"""Builds data/ut_reference.sql from the old database's ut_ lookup tables.

An earlier database of this project defined these lookup tables: CTDA
functions, data types, display transforms, enum and flag kinds with their
values, stored formats. This takes their .sql
exports (schema + INSERTs, one file per table) and writes one file build-db
runs inside its own transaction (so BEGIN / COMMIT are dropped).

usage: python -I tools/import_ut_tables.py <export dir> data/ut_reference.sql
"""
import os
import sys

TABLES = ["ut_data_types", "ut_stored_formats", "ut_disp_transforms", "ut_enum_kinds", "ut_enum_values",
          "ut_flag_kinds", "ut_flag_values", "ut_ctda_functions"]

src, out = sys.argv[1], sys.argv[2]
lines = ["-- Lookup tables carried forward from an earlier database of this project,",
         "-- generated by tools/import_ut_tables.py. Do not edit by hand.", ""]
for t in TABLES:
    with open(os.path.join(src, t + ".sql"), encoding="utf-8") as f:
        for line in f:
            s = line.rstrip("\n")
            if s.strip().upper() in ("BEGIN;", "COMMIT;", "BEGIN TRANSACTION;"):
                continue
            lines.append(s)
    lines.append("")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"wrote {out}: {len(lines)} lines")
