"""Builds data/ut_reference.sql from the earlier database's ut_ lookup tables.

An earlier database of this project defined these lookup tables: CTDA
functions, data types, display transforms, enum and flag kinds with their
values, stored formats. This takes their .sql exports (schema + INSERTs, one
file per table) and writes one file build-db runs inside its own transaction
(so BEGIN / COMMIT are dropped).

It also writes ut_field_links: which field of which record type used which
enum or flag kind in that database (from its st_record_types, st_rt_fs_columns
and st_fs_fields exports, as .csv). build-db binds st_columns by these first,
then by name.

usage: python -I tools/import_ut_tables.py <ut export dir> <st export dir> data/ut_reference.sql
"""
import csv
import os
import sys

TABLES = ["ut_data_types", "ut_stored_formats", "ut_disp_transforms", "ut_enum_kinds", "ut_enum_values",
          "ut_flag_kinds", "ut_flag_values", "ut_ctda_functions"]


def read_csv(folder, name):
    with open(os.path.join(folder, name + ".csv"), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def sql_text(s):
    return "NULL" if s is None else "'" + s.replace("'", "''") + "'"


def field_links(ut_dir, st_dir):
    enum = {r["id"]: r["kind_name"] for r in read_csv(ut_dir, "ut_enum_kinds")}
    flag = {r["id"]: r["kind_name"] for r in read_csv(ut_dir, "ut_flag_kinds")}
    sig = {r["id"]: r["sig"] for r in read_csv(st_dir, "st_record_types")}
    fs = {r["id"]: (sig.get(r["fk_record_type"]), r["fs_sig"]) for r in read_csv(st_dir, "st_rt_fs_columns")}
    links = set()
    for r in read_csv(st_dir, "st_fs_fields"):
        e, g = enum.get(r["fk_lookup_kind"]), flag.get(r["fk_flag_kind"])
        rt, sub = fs.get(r["fk_rt_fs"], (None, None))
        if not (e or g) or not rt or not sub or sub == "Record Header":  # record flags: record_flags_v
            continue
        links.add((rt, sub, r["leaf_id"], e, g))
    return sorted(links, key=lambda x: (x[0], x[1], x[2]))


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    ut_dir, st_dir, out = sys.argv[1:]
    lines = ["-- Lookup tables carried forward from an earlier database of this project,",
             "-- generated by tools/import_ut_tables.py. Do not edit by hand.", ""]
    for t in TABLES:
        with open(os.path.join(ut_dir, t + ".sql"), encoding="utf-8") as f:
            for line in f:
                s = line.rstrip("\n")
                if s.strip().upper() in ("BEGIN;", "COMMIT;", "BEGIN TRANSACTION;"):
                    continue
                lines.append(s)
        lines.append("")
    links = field_links(ut_dir, st_dir)
    lines.append("-- ut_field_links")
    lines.append("CREATE TABLE ut_field_links (record_type TEXT NOT NULL, subrecord TEXT NOT NULL, leaf TEXT NOT NULL,"
                 " enum_kind TEXT, flag_kind TEXT, PRIMARY KEY (record_type, subrecord, leaf)) WITHOUT ROWID;")
    for rt, sub, leaf, e, g in links:
        lines.append(f"INSERT INTO ut_field_links VALUES({sql_text(rt)},{sql_text(sub)},{sql_text(leaf)},"
                     f"{sql_text(e)},{sql_text(g)});")
    lines.append("")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {len(lines)} lines, {len(links)} field links")


if __name__ == "__main__":
    main()
