"""Generates src/unused_subrecords.inc: whole subrecords xEdit labels Unused or
Unknown, which `spf export --conflicts` leaves out. Fields inside a subrecord
are matched by name in the exporter; these have no name in the output.

Sources: xEdit 4.1.5q's priorities (wbUnused elements) and the ground-truth DB's
paths. Local files; the generated .inc is what's committed.

    python -I tools/gen_unused_subrecords.py <XEDIT_CONFLICT_PRIORITIES.json> <ground_truth.db> > src/unused_subrecords.inc
"""
import json
import re
import sqlite3
import sys

pairs = set()
for p in json.load(open(sys.argv[1], encoding="utf-8"))["priorities"]:
    note = p.get("note", "") + " " + p.get("container", "")
    # Only entries tied to one record: "*" rows are shared helpers (INDX, MODT) whose note mentions Unused
    # because of something inside them, and they are real fields.
    if p["record"] != "*" and re.fullmatch(r"[A-Z0-9_]{4}", p.get("path", "")) and re.search(r"\b(wbUnused|Unused|Unknown)\b", note):
        pairs.add((p["record"], p["path"]))
g = sqlite3.connect(f"file:{sys.argv[2]}?mode=ro", uri=True)
for rec, path, sig in g.execute("select distinct record_type, path, field_sig from ground_truth where field_sig<>''"):
    head = path.split(" \\ ")[0]
    if re.match(r"(Unused|Unknown)\b", head, re.I) and re.fullmatch(r"[A-Z0-9_]{4}", sig):
        pairs.add((rec, sig))
print("// Generated by tools/gen_unused_subrecords.py from xEdit's definitions")
print("// (github.com/TES5Edit/TES5Edit). {record type, subrecord}.")
print("// This Source Code Form is subject to the terms of the Mozilla Public License,")
print("// v. 2.0. If a copy of the MPL was not distributed with this file, You can obtain")
print("// one at https://mozilla.org/MPL/2.0/.")
for rec, sig in sorted(pairs):
    print(f'{{"{rec}", "{sig}"}},')
